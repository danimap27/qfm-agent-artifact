"""Paired statistical comparison between the pilot conditions.

Wilcoxon signed-rank tests with Holm-Bonferroni correction across the family
of comparisons, bootstrap confidence intervals for the mean difference, and
Cohen's d_z. Deterministic: the bootstrap uses a fixed seed. Writes a JSON
report and a LaTeX table fragment for the manuscript.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from scipy import stats as scipy_stats

METRICS = ["unsupported_rate", "contradiction_rate", "cf_consistency", "comprehensiveness", "sufficiency"]
COMPARISONS = [
    ("grounded", "free"),
    ("grounded", "single_block"),
    ("grounded", "sabotage"),
    ("grounded", "occlusion_attributions"),
]
BOOTSTRAP_ITERATIONS = 10_000
SEED = 0


def bootstrap_ci(differences: np.ndarray, rng: np.random.Generator) -> tuple[float, float]:
    """Percentile bootstrap interval of the mean difference."""
    draws = rng.choice(differences, size=(BOOTSTRAP_ITERATIONS, differences.size), replace=True)
    means = draws.mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def cohens_dz(differences: np.ndarray) -> float:
    """Standardized mean difference for paired samples."""
    std = float(differences.std(ddof=1))
    return float(differences.mean() / std) if std > 0.0 else 0.0


def holm(p_values: list[float]) -> list[float]:
    """Holm-Bonferroni adjusted p-values, order preserving."""
    count = len(p_values)
    order = np.argsort(p_values)
    adjusted = np.empty(count)
    running = 0.0
    for rank, index in enumerate(order):
        candidate = min(1.0, (count - rank) * p_values[index])
        running = max(running, candidate)
        adjusted[index] = running
    return [float(value) for value in adjusted]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--metrics", default="results/pilot/metrics.json")
    parser.add_argument("--out", default="results/pilot/stats.json")
    parser.add_argument("--tex", default="paper/tables/tab_pilot.tex")
    args = parser.parse_args()

    payload = json.loads(Path(args.metrics).read_text())
    per_record = payload["per_record"]
    by_key = {(row["request_id"], row["condition"]): row for row in per_record}
    request_ids = sorted({row["request_id"] for row in per_record})

    rng = np.random.default_rng(SEED)
    tests: list[dict] = []
    for metric in METRICS:
        for condition_a, condition_b in COMPARISONS:
            values_a, values_b = [], []
            for request_id in request_ids:
                row_a = by_key.get((request_id, condition_a))
                row_b = by_key.get((request_id, condition_b))
                if row_a is None or row_b is None:
                    continue
                value_a, value_b = row_a.get(metric), row_b.get(metric)
                if value_a is None or value_b is None:
                    continue
                values_a.append(float(value_a))
                values_b.append(float(value_b))
            test = {"metric": metric, "comparison": f"{condition_a} vs {condition_b}", "n": len(values_a)}
            if len(values_a) < 5:
                test["note"] = "insufficient pairs"
                tests.append(test)
                continue
            array_a = np.asarray(values_a)
            array_b = np.asarray(values_b)
            differences = array_a - array_b
            if np.allclose(differences, 0.0):
                statistic, p_value = 0.0, 1.0
            else:
                statistic, p_value = scipy_stats.wilcoxon(differences, alternative="two-sided")
            low, high = bootstrap_ci(differences, rng)
            test.update(
                {
                    "mean_a": round(float(array_a.mean()), 4),
                    "mean_b": round(float(array_b.mean()), 4),
                    "mean_diff": round(float(differences.mean()), 4),
                    "ci_low": round(low, 4),
                    "ci_high": round(high, 4),
                    "p_raw": float(p_value),
                    "statistic": float(statistic),
                    "dz": round(cohens_dz(differences), 3),
                }
            )
            tests.append(test)

    computable = [test for test in tests if "p_raw" in test]
    adjusted = holm([test["p_raw"] for test in computable])
    for test, value in zip(computable, adjusted):
        test["p_holm"] = value

    out_path = Path(args.out)
    out_path.write_text(json.dumps({"tests": tests, "bootstrap_iterations": BOOTSTRAP_ITERATIONS, "seed": SEED}, indent=2))

    tex_lines = [
        "% Generated by code/stats/compare.py",
        "\\begin{tabular}{llrrrrrr}",
        "\\hline",
        "Metric & Comparison & n & Mean A & Mean B & Diff & 95\\% CI & $p_{Holm}$ \\\\",
        "\\hline",
    ]
    for test in tests:
        metric = test["metric"].replace("_", "\\_")
        comparison = test["comparison"].replace("_", "\\_")
        if "p_raw" in test:
            ci = f"[{test['ci_low']:.2f}, {test['ci_high']:.2f}]"
            tex_lines.append(
                f"{metric} & {comparison} & {test['n']} & {test['mean_a']:.3f} & {test['mean_b']:.3f} & "
                f"{test['mean_diff']:.3f} & {ci} & {test['p_holm']:.3g} \\\\"
            )
        else:
            tex_lines.append(f"{metric} & {comparison} & {test['n']} & -- & -- & -- & -- & -- \\\\")
    tex_lines += ["\\hline", "\\end{tabular}", ""]
    tex_path = Path(args.tex)
    tex_path.parent.mkdir(parents=True, exist_ok=True)
    tex_path.write_text("\n".join(tex_lines))

    print(f"{'metric':<22} {'comparison':<30} {'n':>3} {'diff':>8} {'p_holm':>10} {'dz':>7}")
    for test in tests:
        if "p_raw" in test:
            print(
                f"{test['metric']:<22} {test['comparison']:<30} {test['n']:>3} "
                f"{test['mean_diff']:>8.3f} {test['p_holm']:>10.3g} {test['dz']:>7.3f}"
            )
        else:
            print(f"{test['metric']:<22} {test['comparison']:<30} {test['n']:>3} {'--':>8}")
    print(f"wrote {out_path} and {tex_path}")


if __name__ == "__main__":
    main()
