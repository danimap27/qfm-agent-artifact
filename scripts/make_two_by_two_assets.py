"""Table and figure for the evidence x contract decomposition."""
from __future__ import annotations

import json
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "results/post_freeze/two_by_two.json").read_text())

MODELS = [("qwen35", "Compact"), ("llama31_8b", "Instruction"), ("gemma3_27b", "Dense")]
CELLS = ["free", "evidence_only", "cite_only", "grounded"]
LABELS = {
    "free": "no evidence, no contract",
    "evidence_only": "evidence, no contract",
    "cite_only": "contract, no evidence",
    "grounded": "evidence and contract",
}

plt.rcParams.update({"font.family": "serif", "font.size": 8, "axes.linewidth": 0.6})

fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9))
width = 0.2
x = np.arange(len(MODELS))
# Hatching keeps the four cells apart in greyscale and for colour-blind readers.
HATCH = {"free": "", "evidence_only": "///", "cite_only": "...", "grounded": "xxx"}
for ax, metric, ylabel, tag in ((axes[0], "ur", "Unsupported rate", "(a)"), (axes[1], "claims", "Verifiable claims per explanation", "(b)")):
    for index, cell in enumerate(CELLS):
        values = [data[key][cell][metric] for key, _ in MODELS]
        ax.bar(x + (index - 1.5) * width, values, width, label=LABELS[cell], hatch=HATCH[cell], edgecolor="black", linewidth=0.4)
    ax.set_xticks(x)
    ax.set_xticklabels([label for _, label in MODELS])
    ax.set_xlabel("Verbalizer family")
    ax.set_ylabel(ylabel)
    ax.set_title(tag, loc="left", fontsize=8)
    ax.grid(axis="y", linewidth=0.3, alpha=0.5)
    ax.set_axisbelow(True)
    for spine in ("top", "right"):
        ax.spines[spine].set_visible(False)
axes[0].set_ylim(0, 1.15)
axes[1].set_ylim(0, 8.6)
handles, labels = axes[0].get_legend_handles_labels()
fig.legend(handles, labels, fontsize=6.5, frameon=False, ncol=4, loc="lower center", bbox_to_anchor=(0.5, 0.0))
fig.tight_layout(rect=(0, 0.08, 1, 1))
target = ROOT / "paper/figures/fig10_two_by_two.pdf"
fig.savefig(target, bbox_inches="tight")
print(f"wrote {target}")

lines = [
    "% Generated by scripts/make_two_by_two_assets.py from results/post_freeze/two_by_two.json",
    "\\begin{tabular}{llrrrr}",
    "\\hline",
    "Family & Condition & UR & Claims & Prominence & $n$ \\\\",
    "\\hline",
]
for key, label in MODELS:
    for cell in CELLS:
        values = data[key][cell]
        prominence = values["prominence"]
        prominence_text = "--" if prominence is None else f"{prominence:.3f}"
        lines.append(
            f"{label} & {cell.replace('_', chr(92) + '_')} & {values['ur']:.3f} & {values['claims']:.2f} & "
            f"{prominence_text} & {data[key]['n_seeds']} \\\\"
        )
    lines.append("\\hline")
lines.append("\\end{tabular}")
(ROOT / "paper/tables/tab_two_by_two.tex").write_text("\n".join(lines) + "\n")
print("wrote paper/tables/tab_two_by_two.tex")
